"use client";

import { useState, Suspense } from "react";
import { useRouter, useSearchParams } from "next/navigation";
import { Card, CardContent, CardHeader, CardTitle, CardDescription } from "@/components/ui/card";
import { Input } from "@/components/ui/input";
import { Button } from "@/components/ui/button";
import { AlertCircle, ShieldCheck, KeyRound, ArrowLeft, Loader2, LogOut } from "lucide-react";
import { Logo } from "@/components/logo";
import { createClient } from "@/lib/supabase/client";
import Link from "next/link";

function User2FAChallengeForm() {
  const router = useRouter();
  const searchParams = useSearchParams();
  const next = searchParams.get("next") || "/dashboard";

  const [code, setCode] = useState("");
  const [recoveryCode, setRecoveryCode] = useState("");
  const [useRecovery, setUseRecovery] = useState(false);
  const [loading, setLoading] = useState(false);
  const [loggingOut, setLoggingOut] = useState(false);
  const [errorMsg, setErrorMsg] = useState<string | null>(null);

  const handleSubmit = async (e: React.FormEvent<HTMLFormElement>) => {
    e.preventDefault();
    setErrorMsg(null);
    setLoading(true);

    try {
      const rawInput = useRecovery ? recoveryCode.trim() : code.replace(/\s+/g, "").trim();

      if (!rawInput) {
        throw new Error(useRecovery ? "Please enter a recovery code." : "Please enter the 6-digit authenticator code.");
      }

      const res = await fetch("/api/auth/2fa/login-verify", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          code: rawInput,
          next: next,
        }),
      });

      const data = await res.json().catch(() => ({}));

      if (!res.ok || !data.success) {
        throw new Error(data.error || "2FA verification failed. Please check your code.");
      }

      // Successful verification! Redirect to destination
      const targetDestination = data.redirect || next;
      router.push(targetDestination);
      router.refresh();

      setTimeout(() => {
        if (window.location.pathname.includes("/auth/2fa")) {
          window.location.assign(targetDestination);
        }
      }, 500);
    } catch (err: any) {
      setErrorMsg(err.message || "An unexpected error occurred during verification.");
      setLoading(false);
    }
  };

  const handleSignOut = async () => {
    setLoggingOut(true);
    try {
      const supabase = createClient();
      await supabase.auth.signOut();
    } catch (_) {}
    window.location.href = "/login";
  };

  return (
    <div className="min-h-screen flex items-center justify-center p-4 bg-slate-50 dark:bg-[#07090e] text-slate-900 dark:text-slate-100 transition-colors">
      <Card className="w-full max-w-md bg-white dark:bg-[#0b0e17] border-slate-200 dark:border-[#1e2640] shadow-xl">
        <CardHeader className="space-y-3">
          <div className="flex items-center justify-between">
            <Link href="/" title="Back to Wayones">
              <Logo variant="desktop" priority />
            </Link>
            <div className="w-9 h-9 rounded-lg bg-blue-50 dark:bg-blue-950/60 border border-blue-200 dark:border-blue-800/40 flex items-center justify-center shrink-0">
              <ShieldCheck className="w-5 h-5 text-blue-600 dark:text-blue-400" />
            </div>
          </div>
          <div>
            <CardTitle className="text-2xl font-bold text-slate-900 dark:text-white">Two-Factor Authentication</CardTitle>
            <CardDescription className="text-slate-600 dark:text-slate-400">
              {useRecovery
                ? "Enter one of your 8-character recovery backup codes to access your account."
                : "Enter the 6-digit verification code generated by your authenticator app (Google Authenticator, Authy, etc.)."}
            </CardDescription>
          </div>
        </CardHeader>
        <CardContent className="space-y-4">
          {errorMsg && (
            <div className="p-3 bg-red-50 dark:bg-red-950/80 border border-red-200 dark:border-red-500/50 text-red-700 dark:text-red-200 rounded-lg text-sm flex items-start gap-2 break-words">
              <AlertCircle className="w-5 h-5 text-red-600 dark:text-red-400 shrink-0 mt-0.5" />
              <div className="space-y-1">
                <p className="font-semibold text-red-800 dark:text-red-300">Verification Failed</p>
                <p>{errorMsg}</p>
              </div>
            </div>
          )}

          <form onSubmit={handleSubmit} className="space-y-4">
            {!useRecovery ? (
              <div className="space-y-2">
                <label className="text-sm font-medium text-slate-700 dark:text-slate-300">6-Digit Authenticator Code</label>
                <Input
                  id="user-2fa-code-input"
                  name="code"
                  type="text"
                  inputMode="numeric"
                  autoComplete="one-time-code"
                  pattern="[0-9]*"
                  maxLength={8}
                  placeholder="123456"
                  autoFocus
                  required
                  value={code}
                  onChange={(e) => setCode(e.target.value)}
                  className="bg-slate-50 dark:bg-slate-900 border-slate-300 dark:border-slate-700 text-slate-900 dark:text-white font-mono text-center tracking-widest text-lg h-12"
                />
              </div>
            ) : (
              <div className="space-y-2">
                <label className="text-sm font-medium text-slate-700 dark:text-slate-300">One-Time Recovery Code</label>
                <Input
                  id="user-2fa-recovery-input"
                  name="recoveryCode"
                  type="text"
                  placeholder="XXXX-XXXX"
                  autoFocus
                  required
                  value={recoveryCode}
                  onChange={(e) => setRecoveryCode(e.target.value)}
                  className="bg-slate-50 dark:bg-slate-900 border-slate-300 dark:border-slate-700 text-slate-900 dark:text-white font-mono text-center tracking-wider text-base h-12"
                />
              </div>
            )}

            <Button
              id="user-2fa-submit-btn"
              type="submit"
              className="w-full bg-blue-600 hover:bg-blue-500 text-white font-medium h-11"
              disabled={loading || loggingOut}
            >
              {loading ? (
                <span className="flex items-center gap-2">
                  <Loader2 className="w-4 h-4 animate-spin" />
                  Verifying Code...
                </span>
              ) : (
                "Verify & Continue"
              )}
            </Button>
          </form>

          <div className="pt-2 border-t border-slate-200 dark:border-slate-800 flex flex-col gap-2">
            <Button
              type="button"
              variant="ghost"
              size="sm"
              onClick={() => {
                setUseRecovery(!useRecovery);
                setErrorMsg(null);
                setCode("");
                setRecoveryCode("");
              }}
              className="w-full text-xs text-blue-600 dark:text-blue-400 hover:text-blue-700 dark:hover:text-blue-300 hover:bg-blue-50 dark:hover:bg-slate-800"
            >
              {useRecovery ? (
                <span className="flex items-center gap-1.5">
                  <ArrowLeft className="w-3.5 h-3.5" /> Use 6-Digit Authenticator Code
                </span>
              ) : (
                <span className="flex items-center gap-1.5">
                  <KeyRound className="w-3.5 h-3.5" /> Lost access? Use Recovery Backup Code
                </span>
              )}
            </Button>

            <button
              type="button"
              onClick={handleSignOut}
              disabled={loggingOut}
              className="flex items-center justify-center gap-1.5 text-center text-xs text-slate-500 dark:text-slate-400 hover:text-red-600 dark:hover:text-red-400 transition-colors py-1 cursor-pointer"
            >
              <LogOut className="w-3.5 h-3.5" />
              {loggingOut ? "Signing out..." : "Cancel & Return to Login"}
            </button>
          </div>
        </CardContent>
      </Card>
    </div>
  );
}

export default function User2FAChallengePage() {
  return (
    <Suspense
      fallback={
        <div className="min-h-screen flex items-center justify-center p-4 bg-slate-50 dark:bg-[#07090e] text-slate-900 dark:text-slate-100">
          <Loader2 className="w-8 h-8 animate-spin text-blue-500" />
        </div>
      }
    >
      <User2FAChallengeForm />
    </Suspense>
  );
}
