'use server';

import { z } from 'zod';

const CryptoPricesFlowInputSchema = z.object({
  symbols: z.array(z.string().trim().min(1)).min(1).describe('Cryptocurrency symbols to price in USD.'),
});
export type CryptoPricesFlowInput = z.infer<typeof CryptoPricesFlowInputSchema>;

const CryptoPricesFlowOutputSchema = z.object({
  prices: z.record(z.string(), z.number().finite().positive()),
});
export type CryptoPricesFlowOutput = z.infer<typeof CryptoPricesFlowOutputSchema>;

const COINGECKO_IDS: Record<string, string> = {
  BTC: 'bitcoin',
  ETH: 'ethereum',
  LTC: 'litecoin',
  USDT: 'tether',
  BNB: 'binancecoin',
  TRX: 'tron',
  SOL: 'solana',
  XRP: 'ripple',
  ADA: 'cardano',
  DOGE: 'dogecoin',
};

/**
 * Fetch market prices from a deterministic market-data source.
 * Prices are financial inputs, so they must not be generated by an LLM.
 */
export async function getPrices(input: CryptoPricesFlowInput): Promise<CryptoPricesFlowOutput> {
  const parsed = CryptoPricesFlowInputSchema.parse(input);
  const symbols = [...new Set(parsed.symbols.map((symbol) => symbol.toUpperCase()))];
  const unsupported = symbols.filter((symbol) => !COINGECKO_IDS[symbol]);
  if (unsupported.length > 0) {
    throw new Error(`Unsupported cryptocurrency symbols: ${unsupported.join(', ')}`);
  }

  const ids = symbols.map((symbol) => COINGECKO_IDS[symbol]);
  const url = new URL('https://api.coingecko.com/api/v3/simple/price');
  url.searchParams.set('ids', ids.join(','));
  url.searchParams.set('vs_currencies', 'usd');

  const response = await fetch(url.toString(), {
    headers: { accept: 'application/json' },
    cache: 'no-store',
    signal: AbortSignal.timeout(8000),
  });
  if (!response.ok) {
    throw new Error(`Market price provider returned HTTP ${response.status}`);
  }

  const data: unknown = await response.json();
  const parsedData = z.record(z.object({ usd: z.number().finite().positive() })).parse(data);
  const prices: Record<string, number> = {};
  for (const symbol of symbols) {
    const value = parsedData[COINGECKO_IDS[symbol]]?.usd;
    if (typeof value !== 'number' || !Number.isFinite(value) || value <= 0) {
      throw new Error(`Market price unavailable for ${symbol}`);
    }
    prices[symbol] = value;
  }
  return { prices };
}
